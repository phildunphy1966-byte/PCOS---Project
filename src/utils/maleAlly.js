export function getMaleMythCategories(items = []) {
  const seen = new Set();
  const categories = ["All"];
  for (const item of items) {
    if (item?.category && !seen.has(item.category)) {
      seen.add(item.category);
      categories.push(item.category);
    }
  }
  return categories;
}

export function filterMaleMyths(items = [], { category = "All", verdict = "All" } = {}) {
  return items.filter((item) => {
    const categoryMatch = category === "All" || item.category === category;
    const verdictMatch = verdict === "All" || item.verdict === verdict;
    return categoryMatch && verdictMatch;
  });
}

export function getMaleSupportRole(roleId) {
  return (
    MALE_SUPPORT_ROLES.find((role) => role.id === roleId) ||
    MALE_SUPPORT_ROLES[0]
  );
}

export function countRevealedMaleMyths(revealedMap = {}, items = []) {
  if (!revealedMap || typeof revealedMap !== "object") return 0;
  const validIds = new Set(items.map((item) => item.id));
  let count = 0;
  for (const [id, isRevealed] of Object.entries(revealedMap)) {
    if (isRevealed && validIds.has(id)) count += 1;
  }
  return count;
}
